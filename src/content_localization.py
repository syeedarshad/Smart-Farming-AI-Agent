def localize_content(text: str, lang_code: str, *, fallback: bool = True) -> str:
    """Translate an exact known dataset string; preserve it otherwise."""
    if not isinstance(text, str) or lang_code == "en":
        return text
    translated = CONTENT_TRANSLATIONS.get(text, {}).get(lang_code)
    if translated:
        return translated
    return text if fallback else ""


def safety_label(key: str, lang_code: str) -> str:
    """Localized weather/pesticide UI labels with English fallback."""
    return SAFETY_LABELS.get(lang_code, SAFETY_LABELS["en"]).get(
        key, SAFETY_LABELS["en"].get(key, key)
    )
